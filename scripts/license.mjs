#!/usr/bin/env node
// Datasetless license tool — run on YOUR machine only. Never commit .license/.
//
//   node scripts/license.mjs keygen
//       Creates a new signing key pair. The private key goes to .license/private.pem
//       and the public key is written into src/license-key.js (commit that file).
//
//   node scripts/license.mjs issue --plan pro --org "Acme Inc" --domains acme.com,*.acme.com --days 365
//       Prints a license key for a customer. Omit --domains to allow any domain.
//
//   node scripts/license.mjs inspect <key>
import { generateKeyPairSync, createPrivateKey, sign } from 'node:crypto';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const privPath = process.env.DATASETLESS_LICENSE_KEY_FILE || join(root, '.license', 'private.pem');
const pubFile = join(root, 'src', 'license-key.js');
const b64url = (buf) => Buffer.from(buf).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

const [cmd, ...rest] = process.argv.slice(2);
const args = {};
for (let i = 0; i < rest.length; i++) if (rest[i].startsWith('--')) args[rest[i].slice(2)] = rest[i + 1]?.startsWith('--') || rest[i + 1] == null ? true : rest[++i];

if (cmd === 'keygen') {
  if (existsSync(privPath) && !args.force) {
    console.error(`A private key already exists at ${privPath}. Re-run with --force to replace it (old licenses will stop working).`);
    process.exit(1);
  }
  const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  mkdirSync(dirname(privPath), { recursive: true });
  writeFileSync(privPath, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  const spki = b64url(publicKey.export({ type: 'spki', format: 'der' }));
  writeFileSync(pubFile, `// Public key used to verify license keys. Generated by scripts/license.mjs keygen.\n// Safe to publish. The matching private key must stay secret.\nexport const LICENSE_PUBLIC_KEY = '${spki}';\n`);
  console.log(`Private key: ${privPath}  (keep it secret and backed up)`);
  console.log(`Public key written to src/license-key.js — rebuild and redeploy the app.`);
} else if (cmd === 'issue') {
  if (!existsSync(privPath)) { console.error('No private key. Run: node scripts/license.mjs keygen'); process.exit(1); }
  const plan = String(args.plan || 'pro');
  if (!['pro', 'business'].includes(plan)) { console.error('--plan must be pro or business'); process.exit(1); }
  const days = Number(args.days || 365);
  const exp = new Date(Date.now() + days * 864e5).toISOString().slice(0, 10);
  const payload = { v: 1, plan, org: String(args.org || ''), domains: args.domains && args.domains !== true ? String(args.domains).split(',').map((d) => d.trim()).filter(Boolean) : [], exp, iat: new Date().toISOString().slice(0, 10) };
  const head = `DSL1.${b64url(JSON.stringify(payload))}`;
  const key = createPrivateKey(readFileSync(privPath));
  const sig = sign('sha256', Buffer.from(head), { key, dsaEncoding: 'ieee-p1363' });
  console.log(`${head}.${b64url(sig)}`);
  console.error(`\n${plan} license for ${payload.org || '(no org)'} · domains: ${payload.domains.join(', ') || 'any'} · expires ${exp}`);
} else if (cmd === 'inspect') {
  const p = String(rest[0] || '').split('.');
  console.log(JSON.parse(Buffer.from(p[1] || '', 'base64url').toString()));
} else {
  console.log('Usage: node scripts/license.mjs keygen | issue --plan pro --org "Acme" --domains acme.com --days 365 | inspect <key>');
}
